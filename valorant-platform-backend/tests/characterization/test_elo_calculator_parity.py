# --- Legacy persistence semantics (services.py round(..., 0)) -----------------


def test_persisted_round_zero_order_rounds_the_difference():
    """Mirrors legacy services.py persistence exactly — the ORDER matters:
    - competitive_elo / elo_after: round(new_elo, 0)
    - elo_before:                   round(before, 0)
    - elo_change:                   round(after - before, 0)  # difference FIRST,
                                    # then round (NOT round(after,0) - round(before,0))

    Non-integer ratings make the order observable: the winner's new rating
    1502.895809684091 rounds to 1503 but the change is 2.3958 -> 2.0, whereas
    `round(after, 0) - round(before, 0)` would yield 1503 - 1500 = 3.0.
    """
    winner_elo, loser_elo = 1500.5, 1000.5
    new_w, new_l = E.calculate_new_elo(winner_elo, loser_elo, 10, 5)

    # competitive_elo / elo_after: round(new_elo, 0)
    assert round(new_w, 0) == 1503.0
    assert round(new_l, 0) == 997.0

    # elo_before: round(before, 0)  (1500.5 -> 1500 via banker's rounding)
    assert round(winner_elo, 0) == 1500.0
    assert round(loser_elo, 0) == 1000.0

    # elo_change: round(after - before, 0) — computed from the UNROUNDED inputs
    assert round(new_w - winner_elo, 0) == 2.0
    assert round(new_l - loser_elo, 0) == -3.0

    # The legacy order genuinely differs from the naive difference-of-rounds:
    legacy_order = round(new_w - winner_elo, 0)
    naive_order = round(new_w, 0) - round(winner_elo, 0)
    assert legacy_order == 2.0
    assert naive_order == 3.0
    assert legacy_order != naive_order


