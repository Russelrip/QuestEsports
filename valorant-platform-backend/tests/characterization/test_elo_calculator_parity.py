def test_calculate_new_elo_equal_ratings_bo1():
    # K=40 both, E=0.5 both. winner_rounds=13, loser_rounds=0 -> round_diff 13,
    # which is in the stomp bucket (>8) -> performance_mult 1.5.
    # winner: 40 * (1 - 0.5) * 1.5 + upset 5 = 35
    # loser:  40 * (0 - 0.5) * 1.5 = -30
    new_w, new_l = E.calculate_new_elo(1000.0, 1000.0, 5, 5)
    assert new_w == pytest.approx(1035.0, abs=1e-9)
    assert new_l == pytest.approx(970.0, abs=1e-9)
    # The +5 upset bonus is present for the winner
    assert new_w - (1000.0 + 40 * (1 - E.expected_score(1000.0, 1000.0)) * 1.5) == pytest.approx(5.0, abs=1e-9)


