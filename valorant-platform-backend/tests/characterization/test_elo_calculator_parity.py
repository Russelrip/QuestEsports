"""Characterization tests pinning exact numerical parity with the legacy ELO module.

`app/legacy/elo_calculator.py` is a byte-for-byte copy of the sibling repo's
`valorant-lk-elo/elo_calculator.py` (255 lines, verified with
`git diff --no-index`). The legacy README is known to disagree with the code,
so the *code* is the source of truth.

Golden values below were generated by EXECUTING the copied module with the
project-local interpreter (Python 3.14.6, project `.venv`) — see the Task 10
report for the generator output. Each test recomputes the value through the
module and pins it with `pytest.approx(abs=1e-9)`; one test
(`test_full_precision_float_parity`) additionally asserts full float precision.

Anything relying on legacy *persistence* behavior (the `round(..., 0)`
semantics of `services.py`) is pinned separately in
`test_persisted_round_zero_order_rounds_the_difference`.
"""

import pytest

from app.legacy.elo_calculator import EloCalculator

E = EloCalculator


def assert_almost_equal(actual, desired, decimal=None):
    """Full-precision float comparison (decimal=None == exact `==`)."""
    if decimal is None:
        assert actual == desired, f"{actual!r} != {desired!r}"
    else:
        assert round(actual, decimal) == round(desired, decimal), (
            f"{actual!r} != {desired!r}"
        )


