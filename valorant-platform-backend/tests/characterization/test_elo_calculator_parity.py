def test_winner_loser_asymmetric_k():
    """Winner and loser use their OWN K factors (winner 10 matches K=30, loser
    5 matches K=40)."""
    k_w = E.get_k_factor(10)
    k_l = E.get_k_factor(5)
    assert (k_w, k_l) == (30, 40)
    e_w = E.expected_score(1500.0, 1000.0)
    e_l = E.expected_score(1000.0, 1500.0)
    perf = E.get_round_differential_multiplier(13, 0)
    assert perf == pytest.approx(1.5, abs=1e-9)
    expected_new_w = 1500.0 + k_w * (1 - e_w) * perf
    expected_new_l = 1000.0 + k_l * (0 - e_l) * perf
    new_w, new_l = E.calculate_new_elo(1500.0, 1000.0, 10, 5)
    assert new_w == pytest.approx(expected_new_w, abs=1e-9)
    assert new_l == pytest.approx(expected_new_l, abs=1e-9)


